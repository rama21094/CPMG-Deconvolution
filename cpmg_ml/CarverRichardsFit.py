# Parse data
lines = data.split('\n')[1:]
nu_cpmg = np.array([float(line.split(',')[1]) for line in lines])
R2_eff = np.array([float(line.split(',')[2]) for line in lines])

def cr72(nu_cpmg, pb, kex, dw, R20):
    pa = 1.0 - pb
    # EXACT 15N Conversion: 600 MHz 1H -> 60.79 MHz 15N
    dw_rad = dw * 60.79 * 2.0 * np.pi 
    
    tcp = 1.0 / (4.0 * nu_cpmg)
    psi = kex**2 - dw_rad**2
    zeta = -2.0 * dw_rad * (pa - pb) * kex
    
    root_term = np.sqrt(psi**2 + zeta**2)
    D_plus = 0.5 * (1.0 + psi / root_term)
    D_minus = 0.5 * (-1.0 + psi / root_term)
    
    eta_plus = tcp * np.sqrt(0.5 * (psi + root_term))
    eta_minus = tcp * np.sqrt(0.5 * (-psi + root_term))
    
    cosh_arg = np.clip(D_plus * np.cosh(2.0 * eta_plus) - D_minus * np.cos(2.0 * eta_minus), 1.0, np.inf)
    
    return R20 + 0.5 * kex - (1.0 / (4.0 * tcp)) * np.arccosh(cosh_arg)

# Force the optimizer into the right physical domain
# bounds: (min_array, max_array)
# Max pB is strictly capped at 0.15 to avoid symmetry traps
bounds = ([0.001, 10.0, 0.5, 1.0], [0.15, 3000.0, 10.0, 20.0])

# Starting guesses anchored near the high-frequency asymptote (min R2_eff)
R20_guess = np.min(R2_eff)
p0 = [0.05, 500.0, 2.5, R20_guess] 

